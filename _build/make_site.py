# -*- coding: utf-8 -*-
"""Assemble the deployable site from the built HTML files.

The pages one level up are made for opening off disk, so they carry two things
a hosted site should not: filenames with spaces (which become %20 in every
shared link) and pointers into _build/, which holds the pipeline and has no
business being published. This writes a clean copy into site/:

  Part 1.html  ->  part1.html          _build/ links dropped
  index.html   ->  index.html          + favicon, description, social tags

Everything it needs comes from site.json -- the same manifest build.py reads,
so the two can never disagree about which pages exist. Nothing here edits the
originals: run build.py first, then this.

    py -3 make_site.py
"""
import json, os, re, shutil, sys

SP = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(SP)
OUT = os.path.join(ROOT, 'site')

with open(os.path.join(SP, 'site.json'), encoding='utf-8') as fh:
    SITE = json.load(fh)

COURSE = SITE.get('course', '')
DESC = SITE.get('description', COURSE)
# `web` is the URL-safe name this page is served under. It exists because `out`
# is chosen for someone browsing the folder on disk -- "Part 3.html", with a
# space and a capital -- and that makes an ugly, percent-escaped, case-sensitive
# URL. Omitting it just serves the page under its on-disk name.
PAGES = {p['out']: p.get('web', p['out']) for p in SITE['pages']}

# The pages are self-contained -- images inlined, MathML instead of a formula
# library -- so nothing needs to be fetched from another origin, and the policy
# says exactly that. The one exception is the comment box: when the manifest
# names a project, its origin is added to connect-src and nothing else moves.
# script-src stays closed because the comments talk to a REST endpoint through
# plain fetch, with no SDK loaded from a CDN.
_C = SITE.get('comments') or {}
CONNECT = (' ' + _C['url'].rstrip('/')) if _C.get('url') and _C.get('anon_key') else ''
CSP = ("default-src 'none'; img-src data:; style-src 'unsafe-inline'; "
       "script-src 'unsafe-inline'; font-src 'none'; base-uri 'none'; "
       "form-action 'none'; frame-ancestors 'none'; connect-src" +
       (CONNECT or " 'none'"))

FAVICON = (
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">'
    '<rect width="64" height="64" rx="14" fill="#d8342a"/>'
    f'<text x="32" y="45" font-family="Georgia,serif" font-size="40"'
    f' fill="#fff" text-anchor="middle">{SITE.get("favicon_glyph", "&#931;")}</text></svg>'
)

# A request for the on-disk name -- an old bookmark, or a link shared before a
# rename -- should still land somewhere. Generated from the manifest so a new
# page gets its redirect for free.
REDIRECTS = '\n'.join(
    f'/{out.replace(" ", "%20")}  /{web}  301'
    for out, web in PAGES.items() if out != web
) + '\n'

NETLIFY_TOML = '''# Static site: the HTML is generated by _build/build.py and committed, so
# Netlify has nothing to build -- it only serves what is in site/.
[build]
  publish = "site"
  command = ""

# Every page is self-contained (images inlined as data URIs, MathML instead of
# a formula library), so there is nothing to fetch from another origin.
[[headers]]
  for = "/*"
  [headers.values]
    Content-Security-Policy = "%s"
    X-Content-Type-Options = "nosniff"
    Referrer-Policy = "no-referrer"
''' % CSP

# netlify.toml sits beside site/, not inside it, so a drag-and-drop deploy of
# the folder alone never sees it and the headers above are silently lost. A
# plain _headers file inside the publish directory is honoured by every deploy
# method, so the two say the same thing and neither can be forgotten.
HEADERS = """/*
  Content-Security-Policy: %s
  X-Content-Type-Options: nosniff
  Referrer-Policy: no-referrer
""" % CSP

NOTFOUND_BODY = '''<!DOCTYPE html>
<html lang="he" dir="rtl"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>הדף לא נמצא — ''' + COURSE + '''</title>
<link rel="icon" href="favicon.svg">
<style>
body{margin:0;min-height:100vh;display:flex;align-items:center;justify-content:center;
  background:#f6f7f9;color:#16181d;font-family:"Segoe UI",Arial,sans-serif;text-align:center}
.card{background:#fff;border:1px solid #dfe3ea;border-radius:14px;padding:2.5rem 3rem;
  box-shadow:0 2px 14px rgba(0,0,0,.06)}
h1{margin:0 0 .4rem;font-size:1.6rem} p{color:#5b6472;margin:0 0 1.2rem}
a{display:inline-block;padding:.5rem 1.1rem;border-radius:999px;background:#d8342a;
  color:#fff;text-decoration:none;font-weight:600}
@media (prefers-color-scheme:dark){
  body{background:#15171c;color:#e8eaee}
  .card{background:#1c1f25;border-color:#2c313a}
  p{color:#9aa3b2}}
</style></head><body>
<div class="card">
  <h1>הדף לא נמצא</h1>
  <p>ייתכן שהקישור ישן, או שהחלק הזה עדיין לא הומר.</p>
  <a href="/">חזרה לעמוד הבית</a>
</div></body></html>
'''


def rewrite(html):
    """Point the internal links at the published filenames and add the head
    tags a shared link needs."""
    # the fragment has to survive: almost every cross-page link in the study
    # files points at a section (`Part 3.html#l311`), and a plain replace of
    # `href="Part 3.html"` misses all of them. They used to reach the page only
    # via the _redirects hop, which is a wasted round trip and disappears
    # entirely if the folder is ever served by something without that file.
    for src, dst in PAGES.items():
        html = re.sub(r'href="%s(#[^"]*)?"' % re.escape(src),
                      lambda m: f'href="{dst}{m.group(1) or ""}"', html)

    # the pipeline documentation and the MathML scratch page are development
    # artefacts. They used to sit under their own "חומר נוסף" heading, which was
    # dropped whole; they now share a contents group with pages that DO get
    # published, so only the individual entries can go.
    html = re.sub(r'\s*<li><a href="_build/[^"]*">.*?</a></li>', '', html)

    head = ('<link rel="icon" href="favicon.svg">\n'
            f'<meta name="description" content="{DESC}">\n'
            '<meta property="og:type" content="website">\n'
            f'<meta property="og:description" content="{DESC}">\n'
            '<meta name="robots" content="noindex, nofollow">\n')
    title = re.search(r'<title>(.*?)</title>', html, re.S)
    if title:
        head += f'<meta property="og:title" content="{title.group(1)}">\n'
    return html.replace('</title>', '</title>\n' + head, 1)


def main():
    if os.path.isdir(OUT):
        shutil.rmtree(OUT)
    os.makedirs(OUT)

    written = []
    for src, dst in PAGES.items():
        path = os.path.join(ROOT, src)
        if not os.path.exists(path):
            print(f'  skip {src} (not built yet)')
            continue
        with open(path, encoding='utf-8') as fh:
            html = fh.read()
        with open(os.path.join(OUT, dst), 'w', encoding='utf-8') as fh:
            fh.write(rewrite(html))
        written.append((dst, os.path.getsize(os.path.join(OUT, dst))))

    for name, text in (('favicon.svg', FAVICON),
                       ('_redirects', REDIRECTS),
                       ('_headers', HEADERS),
                       ('404.html', NOTFOUND_BODY),
                       ('robots.txt', 'User-agent: *\nDisallow: /\n')):
        with open(os.path.join(OUT, name), 'w', encoding='utf-8') as fh:
            fh.write(text)

    with open(os.path.join(ROOT, 'netlify.toml'), 'w', encoding='utf-8') as fh:
        fh.write(NETLIFY_TOML)

    total = 0
    for name, size in written:
        print(f'  {name:16s} {size // 1024:5d} KB')
        total += size
    print(f'SITE: {len(written)} pages, {total // 1024} KB total -> {OUT}')
    print('comments: ' + (('enabled -> ' + _C['url']) if CONNECT else 'off (no project in site.json)'))
    if not any(n == 'index.html' for n, _ in written):
        sys.exit('!! no index.html -- nothing to serve')


if __name__ == '__main__':
    main()
